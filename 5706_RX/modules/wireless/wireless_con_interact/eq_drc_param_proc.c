static u8 eq_replace_en = 0;
static u16 eq_len = 0;
static u8 drc_replace_en = 0;
static u16 drc_len = 0;

static uint8_t eq_param[300];
static uint8_t drc_param[160];

void wl_eq_drc_replace_set(wl_xcfg_str_t * wl_xcfg_ptr)
{
    eq_replace_en = wl_xcfg_ptr->eq_replace_en;
    drc_replace_en = wl_xcfg_ptr->drc_replace_en;

    msg_enqueue(EVT_EQ_PARAM_SET);
    msg_enqueue(EVT_DRC_PARAM_SET);
}

void wl_eq_param_set(void)
{
#if WIRELESS_MIC_EQ_DRC_EN
    if (eq_replace_en) {
        mic_eq_init_by_tbl(eq_param, eq_len);
//    } else {
//        mic_eq_init_by_tbl((u8 *)soft_eq_res_tbl_dft, sizeof(soft_eq_res_tbl_dft));
    }
#endif
}

void wl_drc_param_set(void)
{
#if WIRELESS_MIC_EQ_DRC_EN
    if (drc_replace_en) {
        mic_drc_init_by_tbl(drc_param, drc_len);
    } else {
        mic_drc_init_by_tbl((u8 *)drc_res_tbl_dft, sizeof(drc_res_tbl_dft));
    }
#endif
}

uint wl_eq_prase(u8 *buf, u8 len, inter_ctl_t *ctl)
{
    u16 total_len = GET_LE16(buf) & 0xfff;
    if(total_len > 300) {
        return CMD_STA_ERR;
    }

    ctl->ptr      = &eq_param[0];
    ctl->remain   = total_len;
    ctl->offset   = 0;
    return CMD_STA_RX;
}

void wl_eq_rxdone(inter_ctl_t *ctl)
{
    eq_len = ctl->offset;
    msg_enqueue(EVT_EQ_PARAM_SET);
}

uint wl_drc_prase(u8 *buf, u8 len, inter_ctl_t *ctl)
{
    u16 total_len = GET_LE16(buf) & 0xfff;
    if(total_len > 160) {
        return CMD_STA_ERR;
    }

    ctl->ptr      = &drc_param[0];
    ctl->remain   = total_len;
    ctl->offset   = 0;
    return CMD_STA_RX;
}

void wl_drc_rxdone(inter_ctl_t *ctl)
{
    drc_len = ctl->offset;
    msg_enqueue(EVT_DRC_PARAM_SET);
}

